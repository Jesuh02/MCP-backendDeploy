const lines = [];
lines.push("import Decimal from 'decimal.js';");
lines.push("");
lines.push("Decimal.set({ precision: 64 });");
lines.push("");
lines.push("const MATH_SIGNALS = /calcula|suma|total|multiplica|divide|resta|resultado|costo\\s+total|precio\\s+total|monto\\s+total|redondea|\\xbfcu\\xe1nto|cu\\xe1ntos|cu\\xe1ntas|promedio|media|porcentaje/i;");
lines.push("const HAS_SIGNIFICANT_NUMBERS = /\\d{3,}/;");
lines.push("");
lines.push("const ADVANCED_FORMULA_PATTERNS = [");
lines.push("    /[\\u03A3\\u2211]/,");
lines.push("    /sumatoria/i,");
lines.push("    /serie\\s+geom[e\\xe9]trica/i,");
lines.push("    /serie\\s+aritm[e\\xe9]trica/i,");
lines.push("    /progresi[o\\xf3]n\\s+geom[e\\xe9]trica/i,");
lines.push("    /progresi[o\\xf3]n\\s+aritm[e\\xe9]trica/i,");
lines.push("    /notaci[o\\xf3]n\\s+cient[i\\xed]fica/i,");
lines.push("    /i\\s*=\\s*\\d+\\s*(?:a|to)\\s+\\d+/i,");
lines.push("    /[\\u222b]|integral/i,");
lines.push("    /factorial/i,");
lines.push("    /l[i\\xed]mite|lim\\s*[\\u2192\\u27f6]/i,");
lines.push("    /derivada|d\\/dx/i,");
lines.push("];");
lines.push("");
lines.push("const META_QUESTION_PATTERNS = [");
lines.push("    /d[i\\xed]gito\\s+(?:de\\s+las?\\s+)?(?:centenas?|decenas?|unidades?|miles?|millones?)/i,");
lines.push("    /posici[o\\xf3]n\\s+10[\\u2070\\xb9\\xb2\\xb3\\u2074\\u2075\\u2076\\u2077\\u2078\\u2079]+/i,");
lines.push("    /\\xbfcu[a\\xe1]l\\s+es\\s+el\\s+d[i\\xed]gito/i,");
lines.push("    /cifra\\s+(?:de|en)\\s+(?:la\\s+)?posici[o\\xf3]n/i,");
lines.push("];");
lines.push("");
lines.push("export class QuizMathValidator {");
lines.push("");
lines.push("    static verify(q) {");
lines.push("        if (!q) return q;");
lines.push("        var text = q.question;");
lines.push("        if (!text || typeof text !== 'string') return q;");
lines.push("        var lower = text.toLowerCase();");
lines.push("");
lines.push("        var hasMathSignals = MATH_SIGNALS.test(lower)");
lines.push("            || HAS_SIGNIFICANT_NUMBERS.test(text.replace(/,/g, ''))");
lines.push("            || QuizMathValidator._isAdvancedMathProblem(text);");
lines.push("");
lines.push("        if (!hasMathSignals) return q;");
lines.push("        if (META_QUESTION_PATTERNS.some(function(re) { return re.test(text); })) return q;");
lines.push("");
lines.push("        try {");
lines.push("            var result = QuizMathValidator.computeExpectedAnswer(text);");
lines.push("");
lines.push("            if (q.explanation && typeof q.explanation === 'string') {");
lines.push("                var explResult = QuizMathValidator._tryFromExplanation(q.explanation);");
lines.push("                if (explResult) {");
lines.push("                    result = QuizMathValidator._reconcileResults(result, explResult, q);");
lines.push("                }");
lines.push("            }");
lines.push("");
lines.push("            if (!result) return q;");
lines.push("");
lines.push("            var finalAnswer = QuizMathValidator._applyDecimals(result.value, text);");
lines.push("");
lines.push("            if (q.type === 'fill_in_blank') {");
lines.push("                return QuizMathValidator._verifyFillInBlank(q, finalAnswer, result.steps);");
lines.push("            }");
lines.push("            if (q.type === 'multiple_choice') {");
lines.push("                return QuizMathValidator._verifyMultipleChoice(q, finalAnswer, result.steps);");
lines.push("            }");
lines.push("        } catch (err) {");
lines.push("            console.warn('[MathVerify] Error (non-blocking): ' + err.message);");
lines.push("        }");
lines.push("        return q;");
lines.push("    }");
lines.push("");
lines.push("    static computeExpectedAnswer(text) {");
lines.push("        var arithmetic = QuizMathValidator._tryExplicitArithmetic(text);");
lines.push("        if (arithmetic) return arithmetic;");
lines.push("        var formula = QuizMathValidator._tryFormulaEvaluation(text);");
lines.push("        if (formula) return formula;");
lines.push("        if (QuizMathValidator._isAdvancedMathProblem(text)) return null;");
lines.push("        return QuizMathValidator._tryWordProblem(text) || QuizMathValidator._trySumFallback(text);");
lines.push("    }");
lines.push("");
lines.push("    static _isAdvancedMathProblem(text) {");
lines.push("        return ADVANCED_FORMULA_PATTERNS.some(function(re) { return re.test(text); });");
lines.push("    }");
lines.push("");
lines.push("    static _reconcileResults(computed, explanation, q) {");
lines.push("        if (!computed) return explanation;");
lines.push("        if (!explanation) return computed;");
lines.push("        if (computed.value.equals(explanation.value)) return computed;");
lines.push("        if (computed.fromFormula) return computed;");
lines.push("        if (q.type === 'multiple_choice' && Array.isArray(q.options)) {");
lines.push("            var cMatch = QuizMathValidator._findClosestOption(q.options, computed.value);");
lines.push("            var eMatch = QuizMathValidator._findClosestOption(q.options, explanation.value);");
lines.push("            if (eMatch.within && !cMatch.within) return explanation;");
lines.push("        } else if (q.type === 'fill_in_blank') {");
lines.push("            return explanation;");
lines.push("        }");
lines.push("        return computed;");
lines.push("    }");
lines.push("");
lines.push("    static _verifyFillInBlank(q, finalAnswer, steps) {");
lines.push("        var current = QuizMathValidator._parseDecimal(String(q.correctAnswer));");
lines.push("        if (!current) return q;");
lines.push("        if (!current.equals(finalAnswer)) {");
lines.push("            var tolerance = Decimal.max(finalAnswer.abs().times('0.001'), '0.01');");
lines.push("            if (current.minus(finalAnswer).abs().gt(tolerance)) {");
lines.push("                console.warn('[MathVerify] CORRECTED fill_in_blank: LLM=' + q.correctAnswer + ' -> Computed=' + finalAnswer);");
lines.push("            }");
lines.push("            q.correctAnswer = finalAnswer.toFixed();");
lines.push("            q.explanation = steps.join('. ') + '. Resultado final: ' + finalAnswer + '.';");
lines.push("        }");
lines.push("        return q;");
lines.push("    }");
lines.push("");
lines.push("    static _verifyMultipleChoice(q, finalAnswer, steps) {");
lines.push("        if (!Array.isArray(q.options) || q.options.length === 0) return q;");
lines.push("        var match = QuizMathValidator._findClosestOption(q.options, finalAnswer);");
lines.push("        if (match.within) {");
lines.push("            if (match.index !== q.correctIndex) {");
lines.push("                console.warn('[MathVerify] CORRECTED MC: index ' + q.correctIndex + ' -> ' + match.index);");
lines.push("                q.correctIndex = match.index;");
lines.push("                q.explanation = steps.join('. ') + '. Resultado final: ' + finalAnswer + '.';");
lines.push("            }");
lines.push("            return q;");
lines.push("        }");
lines.push("        console.warn('[MathVerify] REJECTED: No option matches computed=' + finalAnswer);");
lines.push("        return null;");
lines.push("    }");
lines.push("");
lines.push("    // Strategy 1: Explicit Arithmetic");
lines.push("");
lines.push("    static _tryExplicitArithmetic(text) {");
lines.push("        var cleaned = text.replace(/[$\\u20ac\\xa5\\xa3\\u20a1\\u20bf]\\s*/g, '');");
lines.push("        cleaned = cleaned.replace(/(\\d[\\d,]*\\.?\\d*)\\s*\\(\\s*(\\d[\\d,]*\\.?\\d*)\\s*\\)/g, '$1 \\xd7 $2');");
lines.push("        var numberPat = '\\\\d[\\\\d,]*\\\\.?\\\\d*';");
lines.push("        var opPat = '[+\\\\-\\\\xd7*\\\\xf7/]';");
lines.push("        var exprRegex = new RegExp(");
lines.push("            '(' + numberPat + ')\\\\s*(' + opPat + ')\\\\s*(' + numberPat + '(?:\\\\s*' + opPat + '\\\\s*' + numberPat + ')*)', 'g'");
lines.push("        );");
lines.push("        var match = exprRegex.exec(cleaned);");
lines.push("        if (!match) return null;");
lines.push("        var tokens = match[0].split(/\\s*([+\\-\\xd7*\\xf7/])\\s*/).filter(function(t) { return t.trim(); });");
lines.push("        var result = QuizMathValidator._parseDecimal(tokens[0]);");
lines.push("        if (!result) return null;");
lines.push("        var steps = [];");
lines.push("        for (var i = 1; i < tokens.length; i += 2) {");
lines.push("            var op = tokens[i];");
lines.push("            var num = QuizMathValidator._parseDecimal(tokens[i + 1]);");
lines.push("            if (!num) return null;");
lines.push("            var prev = result;");
lines.push("            if (op === '+') result = result.plus(num);");
lines.push("            else if (op === '-') result = result.minus(num);");
lines.push("            else if (op === '\\xd7' || op === '*') result = result.times(num);");
lines.push("            else if (op === '\\xf7' || op === '/') {");
lines.push("                if (num.isZero()) return null;");
lines.push("                result = result.div(num);");
lines.push("            }");
lines.push("            else return null;");
lines.push("            steps.push(prev + ' ' + op + ' ' + num + ' = ' + result);");
lines.push("        }");
lines.push("        var afterExpr = cleaned.substring(cleaned.indexOf(match[0]) + match[0].length);");
lines.push("        var followUps = QuizMathValidator._detectFollowUpOperations(afterExpr);");
lines.push("        for (var fi = 0; fi < followUps.length; fi++) {");
lines.push("            var prevF = result;");
lines.push("            result = followUps[fi].apply(result);");
lines.push("            steps.push(followUps[fi].describe(prevF, result));");
lines.push("        }");
lines.push("        return { value: result, steps: steps };");
lines.push("    }");
lines.push("");
lines.push("    // Strategy 2: Formula Evaluation");
lines.push("");
lines.push("    static _tryFormulaEvaluation(text) {");
lines.push("        var combined = QuizMathValidator._tryCombinedFormula(text);");
lines.push("        if (combined) return combined;");
lines.push("        var summation = QuizMathValidator._tryPolynomialSummation(text);");
lines.push("        if (summation) return summation;");
lines.push("        var geo = QuizMathValidator._tryGeometricSeriesFormula(text);");
lines.push("        if (geo) return geo;");
lines.push("        var arith = QuizMathValidator._tryArithmeticSeriesFormula(text);");
lines.push("        if (arith) return arith;");
lines.push("        return null;");
lines.push("    }");
lines.push("");
lines.push("    static _tryCombinedFormula(text) {");
lines.push("        var summation = QuizMathValidator._tryPolynomialSummation(text);");
lines.push("        var geo = QuizMathValidator._tryGeometricSeriesFormula(text);");
lines.push("        if (summation && geo) {");
lines.push("            var total = summation.value.plus(geo.value);");
lines.push("            return {");
lines.push("                value: total,");
lines.push("                steps: summation.steps.concat(geo.steps).concat(['Total combinado: ' + summation.value + ' + ' + geo.value + ' = ' + total]),");
lines.push("                fromFormula: true,");
lines.push("            };");
lines.push("        }");
lines.push("        var arith = QuizMathValidator._tryArithmeticSeriesFormula(text);");
lines.push("        if (summation && arith) {");
lines.push("            var total2 = summation.value.plus(arith.value);");
lines.push("            return {");
lines.push("                value: total2,");
lines.push("                steps: summation.steps.concat(arith.steps).concat(['Total combinado: ' + summation.value + ' + ' + arith.value + ' = ' + total2]),");
lines.push("                fromFormula: true,");
lines.push("            };");
lines.push("        }");
lines.push("        return null;");
lines.push("    }");
lines.push("");
lines.push("    static _tryPolynomialSummation(text) {");
lines.push("        var sigmaPatterns = [");
lines.push("            /[\\u03A3\\u2211]\\s*\\(?(?:de\\s+)?i\\s*=\\s*(\\d+)\\s+a\\s+(\\d+)\\)?\\s*(?:de\\s+)?\\(([^)]+)\\)/i,");
lines.push("            /sumatoria\\s*(?::\\s*)?[\\u03A3\\u2211]?\\s*\\(?(?:de\\s+)?i\\s*=\\s*(\\d+)\\s+a\\s+(\\d+)\\)?\\s*(?:de\\s+)?\\(([^)]+)\\)/i,");
lines.push("        ];");
lines.push("        for (var p = 0; p < sigmaPatterns.length; p++) {");
lines.push("            var m = sigmaPatterns[p].exec(text);");
lines.push("            if (!m) continue;");
lines.push("            var start = parseInt(m[1], 10);");
lines.push("            var end = parseInt(m[2], 10);");
lines.push("            var polyExpr = m[3];");
lines.push("            if (end < start || end - start > 100000) return null;");
lines.push("            var coeffs = QuizMathValidator._parsePolynomialCoefficients(polyExpr);");
lines.push("            if (!coeffs) return null;");
lines.push("            if (start !== 1 || end > 10000) {");
lines.push("                return QuizMathValidator._computeSummationByIteration(start, end, coeffs, polyExpr);");
lines.push("            }");
lines.push("            var n = new Decimal(end);");
lines.push("            var steps = [];");
lines.push("            var result = new Decimal(0);");
lines.push("            if (!coeffs.a3.isZero()) {");
lines.push("                var sumI3 = n.times(n.plus(1)).div(2).pow(2);");
lines.push("                var term3 = coeffs.a3.times(sumI3);");
lines.push("                result = result.plus(term3);");
lines.push("                steps.push(coeffs.a3 + '*SumI3 = ' + term3);");
lines.push("            }");
lines.push("            if (!coeffs.a2.isZero()) {");
lines.push("                var sumI2 = n.times(n.plus(1)).times(n.times(2).plus(1)).div(6);");
lines.push("                var term2 = coeffs.a2.times(sumI2);");
lines.push("                result = result.plus(term2);");
lines.push("                steps.push(coeffs.a2 + '*n(n+1)(2n+1)/6 = ' + term2);");
lines.push("            }");
lines.push("            if (!coeffs.a1.isZero()) {");
lines.push("                var sumI1 = n.times(n.plus(1)).div(2);");
lines.push("                var term1 = coeffs.a1.times(sumI1);");
lines.push("                result = result.plus(term1);");
lines.push("                steps.push(coeffs.a1 + '*n(n+1)/2 = ' + term1);");
lines.push("            }");
lines.push("            if (!coeffs.a0.isZero()) {");
lines.push("                var term0 = coeffs.a0.times(n);");
lines.push("                result = result.plus(term0);");
lines.push("                steps.push(coeffs.a0 + '*n = ' + term0);");
lines.push("            }");
lines.push("            steps.unshift('Sumatoria(i=1 a ' + end + ') de (' + polyExpr + ')');");
lines.push("            steps.push('Resultado sumatoria: ' + result);");
lines.push("            return { value: result, steps: steps, fromFormula: true };");
lines.push("        }");
lines.push("        return null;");
lines.push("    }");
lines.push("");
lines.push("    static _parsePolynomialCoefficients(expr) {");
lines.push("        var s = expr.trim().replace(/i\\xb3/g, 'i^3').replace(/i\\xb2/g, 'i^2').replace(/\\s+/g, ' ');");
lines.push("        if (/^[\\di]/.test(s)) s = '+' + s;");
lines.push("        var result = { a3: new Decimal(0), a2: new Decimal(0), a1: new Decimal(0), a0: new Decimal(0) };");
lines.push("        var termRe = /([+-])\\s*(\\d*\\.?\\d*)\\s*i\\s*\\^\\s*(\\d+)|([+-])\\s*(\\d*\\.?\\d*)\\s*i(?!\\s*\\^)|([+-])\\s*(\\d+\\.?\\d*)/g;");
lines.push("        var m, matched = false;");
lines.push("        while ((m = termRe.exec(s)) !== null) {");
lines.push("            matched = true;");
lines.push("            if (m[1] !== undefined && m[3] !== undefined) {");
lines.push("                var sign1 = m[1] === '-' ? -1 : 1;");
lines.push("                var coeff1 = (m[2] === '' || m[2] === undefined) ? 1 : parseFloat(m[2]);");
lines.push("                var power = parseInt(m[3], 10);");
lines.push("                if (power <= 3) result['a' + power] = new Decimal(sign1 * coeff1);");
lines.push("            } else if (m[4] !== undefined) {");
lines.push("                var sign2 = m[4] === '-' ? -1 : 1;");
lines.push("                var coeff2 = (m[5] === '' || m[5] === undefined) ? 1 : parseFloat(m[5]);");
lines.push("                result.a1 = new Decimal(sign2 * coeff2);");
lines.push("            } else if (m[6] !== undefined) {");
lines.push("                var sign3 = m[6] === '-' ? -1 : 1;");
lines.push("                result.a0 = new Decimal(sign3 * parseFloat(m[7]));");
lines.push("            }");
lines.push("        }");
lines.push("        return matched ? result : null;");
lines.push("    }");
lines.push("");
lines.push("    static _computeSummationByIteration(start, end, coeffs, polyExpr) {");
lines.push("        if (end - start + 1 > 100000) return null;");
lines.push("        var result = new Decimal(0);");
lines.push("        for (var i = start; i <= end; i++) {");
lines.push("            var di = new Decimal(i);");
lines.push("            result = result.plus(coeffs.a3.times(di.pow(3)).plus(coeffs.a2.times(di.pow(2))).plus(coeffs.a1.times(di)).plus(coeffs.a0));");
lines.push("        }");
lines.push("        return { value: result, steps: ['Sumatoria(i=' + start + ' a ' + end + ') = ' + result], fromFormula: true };");
lines.push("    }");
lines.push("");
lines.push("    static _tryGeometricSeriesFormula(text) {");
lines.push("        if (!/serie\\s+geom[e\\xe9]trica|progresi[o\\xf3]n\\s+geom[e\\xe9]trica|geom[e\\xe9]tric/i.test(text)) return null;");
lines.push("        var a1, r, n;");
lines.push("        var seqRe = /(?:primeros?\\s+)?(\\d+)\\s+t[e\\xe9]rminos?[^.]*?(\\d+\\.?\\d*)\\s*,\\s*(\\d+\\.?\\d*)\\s*,\\s*(\\d+\\.?\\d*)/i;");
lines.push("        var seqM = seqRe.exec(text);");
lines.push("        if (seqM) {");
lines.push("            n = parseInt(seqM[1], 10);");
lines.push("            a1 = new Decimal(seqM[2]);");
lines.push("            var second = new Decimal(seqM[3]);");
lines.push("            var third = new Decimal(seqM[4]);");
lines.push("            if (a1.isZero()) return null;");
lines.push("            r = second.div(a1);");
lines.push("            var r2 = third.div(second);");
lines.push("            if (!r.equals(r2)) return null;");
lines.push("        }");
lines.push("        if (!a1) {");
lines.push("            var paramRe = /a[\\u20811]\\s*=\\s*(\\d+\\.?\\d*).*?r\\s*=\\s*(\\d+\\.?\\d*)/i;");
lines.push("            var paramM = paramRe.exec(text);");
lines.push("            if (paramM) {");
lines.push("                a1 = new Decimal(paramM[1]);");
lines.push("                r = new Decimal(paramM[2]);");
lines.push("                var nRe2 = /(?:primeros?\\s+)?(\\d+)\\s+t[e\\xe9]rminos?|n\\s*=\\s*(\\d+)/i;");
lines.push("                var nM = nRe2.exec(text);");
lines.push("                if (nM) n = parseInt(nM[1] || nM[2], 10);");
lines.push("            }");
lines.push("        }");
lines.push("        if (!a1 || !r || !n || r.eq(1) || n < 1) return null;");
lines.push("        var rPowN = r.pow(n);");
lines.push("        var seriesResult = a1.times(rPowN.minus(1)).div(r.minus(1));");
lines.push("        return {");
lines.push("            value: seriesResult,");
lines.push("            steps: ['Serie geometrica: a1=' + a1 + ', r=' + r + ', n=' + n, 'S_n = ' + a1 + '(' + r + '^' + n + ' - 1)/(' + r + ' - 1) = ' + seriesResult],");
lines.push("            fromFormula: true,");
lines.push("        };");
lines.push("    }");
lines.push("");
lines.push("    static _tryArithmeticSeriesFormula(text) {");
lines.push("        if (!/serie\\s+aritm[e\\xe9]trica|progresi[o\\xf3]n\\s+aritm[e\\xe9]trica/i.test(text)) return null;");
lines.push("        var a1, d, n;");
lines.push("        var seqRe = /(?:primeros?\\s+)?(\\d+)\\s+t[e\\xe9]rminos?[^.]*?(\\d+\\.?\\d*)\\s*,\\s*(\\d+\\.?\\d*)\\s*,\\s*(\\d+\\.?\\d*)/i;");
lines.push("        var seqM = seqRe.exec(text);");
lines.push("        if (seqM) {");
lines.push("            n = parseInt(seqM[1], 10);");
lines.push("            a1 = new Decimal(seqM[2]);");
lines.push("            var second = new Decimal(seqM[3]);");
lines.push("            var third = new Decimal(seqM[4]);");
lines.push("            d = second.minus(a1);");
lines.push("            if (!d.equals(third.minus(second))) return null;");
lines.push("        }");
lines.push("        if (!a1) {");
lines.push("            var paramRe = /a[\\u20811]\\s*=\\s*(\\d+\\.?\\d*).*?d\\s*=\\s*(\\d+\\.?\\d*)/i;");
lines.push("            var paramM = paramRe.exec(text);");
lines.push("            if (paramM) {");
lines.push("                a1 = new Decimal(paramM[1]);");
lines.push("                d = new Decimal(paramM[2]);");
lines.push("                var nRe2 = /(?:primeros?\\s+)?(\\d+)\\s+t[e\\xe9]rminos?|n\\s*=\\s*(\\d+)/i;");
lines.push("                var nM = nRe2.exec(text);");
lines.push("                if (nM) n = parseInt(nM[1] || nM[2], 10);");
lines.push("            }");
lines.push("        }");
lines.push("        if (!a1 || !d || !n || n < 1) return null;");
lines.push("        var nDec = new Decimal(n);");
lines.push("        var seriesResult = nDec.div(2).times(a1.times(2).plus(d.times(nDec.minus(1))));");
lines.push("        return {");
lines.push("            value: seriesResult,");
lines.push("            steps: ['Serie aritmetica: a1=' + a1 + ', d=' + d + ', n=' + n, 'S_n = ' + seriesResult],");
lines.push("            fromFormula: true,");
lines.push("        };");
lines.push("    }");

